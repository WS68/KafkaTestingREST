import { randomUUID } from 'node:crypto';
import { createServer } from 'node:net';
import { Kafka, type Admin, type Consumer, type IHeaders } from 'kafkajs';
import { createConsoleLogger } from '../../src/infrastructure/logging/console-logger.js';
import { startApplication, type RunningApplication } from '../../src/composition/runtime.js';
import { loadConfig } from '../../src/infrastructure/config/load-config.js';
import { prepareConfig } from '../../src/infrastructure/config/prepare-config.js';
import {
  createKafkaPorts,
  type KafkaPorts,
} from '../../src/infrastructure/kafka/create-kafka-ports.js';
import { getBrokerAddress } from './env.js';
import { waitForBroker } from './readiness.js';

const runId = randomUUID();
let nameCounter = 0;
let admin: Admin | undefined;
let adminConnection: Promise<Admin> | undefined;
const generatedTopics = new Set<string>();
const createdTopics = new Set<string>();

const maxTimeoutMs = 15_000;

export interface RawHeader {
  readonly name: string;
  readonly value: Buffer | undefined;
}

export interface RawMessage {
  readonly key: Buffer | undefined;
  readonly value: Buffer | undefined;
  readonly headers: readonly RawHeader[];
}

export interface HttpJsonResponse {
  readonly status: number;
  readonly headers: Readonly<Record<string, string>>;
  readonly body: unknown;
}

function logCleanupFailure(operation: string, error: unknown): void {
  const reason = error instanceof Error ? error.message : String(error);
  console.warn(`[integration] ${operation} failed: ${reason}`);
}

function createAdmin(): Admin {
  return new Kafka({
    clientId: `kafka-testing-rest-integration-harness-${randomUUID()}`,
    brokers: [getBrokerAddress()],
  }).admin();
}

async function getAdmin(): Promise<Admin> {
  if (admin !== undefined) return admin;
  if (adminConnection !== undefined) return adminConnection;

  const candidate = createAdmin();
  adminConnection = candidate
    .connect()
    .then(() => {
      admin = candidate;
      return candidate;
    })
    .catch((error: unknown) => {
      adminConnection = undefined;
      throw error;
    });
  return adminConnection;
}

function assertTimeout(timeoutMs: number): void {
  if (!Number.isInteger(timeoutMs) || timeoutMs <= 0 || timeoutMs > maxTimeoutMs) {
    throw new RangeError(`timeoutMs must be an integer from 1 to ${maxTimeoutMs}`);
  }
}

/** Создаёт имя топика, уникальное для текущего прогона интеграционных тестов. */
export function createUniqueTopicName(prefix: string): string {
  if (prefix.length === 0) throw new Error('Topic prefix must not be empty');
  nameCounter += 1;
  const topic = `${prefix}-${runId}-${nameCounter}`;
  generatedTopics.add(topic);
  return topic;
}

/** Создаёт только топик, имя которого было выдано этим harness. */
export async function createTopic(topic: string, partitions = 1): Promise<void> {
  if (!generatedTopics.has(topic)) {
    throw new Error(`Topic was not generated by this integration harness: ${topic}`);
  }
  if (!Number.isInteger(partitions) || partitions < 1) {
    throw new RangeError('partitions must be a positive integer');
  }

  const created = await (
    await getAdmin()
  ).createTopics({
    topics: [{ topic, numPartitions: partitions }],
    waitForLeaders: true,
  });
  if (created) createdTopics.add(topic);
}

/** Удаляет только топики, успешно созданные этим harness. */
export async function deleteTopics(topics: readonly string[]): Promise<void> {
  const uniqueTopics = [...new Set(topics)];
  for (const topic of uniqueTopics) {
    if (!generatedTopics.has(topic) || !createdTopics.has(topic)) {
      throw new Error(`Refusing to delete a topic not owned by this harness: ${topic}`);
    }
  }
  if (uniqueTopics.length === 0) return;

  await (await getAdmin()).deleteTopics({ topics: uniqueTopics });
  for (const topic of uniqueTopics) createdTopics.delete(topic);
}

async function cleanupTopics(): Promise<void> {
  const topics = [...createdTopics];
  for (const topic of topics) {
    try {
      await deleteTopics([topic]);
    } catch (error: unknown) {
      logCleanupFailure(`Kafka topic cleanup (${topic})`, error);
      createdTopics.delete(topic);
    }
  }

  if (admin !== undefined) {
    try {
      await admin.disconnect();
    } catch (error: unknown) {
      logCleanupFailure('Kafka harness admin disconnect', error);
    } finally {
      admin = undefined;
      adminConnection = undefined;
    }
  }
}

async function getFreePort(): Promise<number> {
  const server = createServer();
  return new Promise<number>((resolve, reject) => {
    const fail = (error: Error): void => {
      server.close(() => reject(error));
    };
    server.once('error', fail);
    server.listen({ host: '127.0.0.1', port: 0 }, () => {
      const address = server.address();
      if (address === null || typeof address === 'string') {
        fail(new Error('Unable to obtain a free HTTP port'));
        return;
      }
      server.close((error) => {
        if (error !== undefined) reject(error);
        else resolve(address.port);
      });
    });
  });
}

export interface TestApplication {
  readonly baseUrl: string;
  readonly shutdown: () => Promise<void>;
  readonly cleanup: () => Promise<void>;
  readonly test: RunningApplication['test'];
}

/** Запускает приложение с реальными KafkaJS-адаптерами и временным HTTP-портом. */
export async function startTestApplication(overrides?: {
  readonly env?: Record<string, string | undefined>;
  readonly groupAdmin?: KafkaPorts['groupAdmin'];
  readonly publisher?: KafkaPorts['publisher'];
  readonly skipBrokerCheck?: boolean;
}): Promise<TestApplication> {
  if (!overrides?.skipBrokerCheck && !(await waitForBroker())) {
    throw new Error('Kafka broker is unavailable at the configured address');
  }

  const port = await getFreePort();
  const env: Record<string, string | undefined> = {
    ...process.env,
    ...overrides?.env,
    KAFKA_TESTING_REST_CLUSTER:
      overrides?.env?.['KAFKA_TESTING_REST_CLUSTER'] ?? getBrokerAddress(),
    KAFKA_TESTING_REST_HTTP_HOST: '127.0.0.1',
    KAFKA_TESTING_REST_HTTP_PORT: String(port),
    KAFKA_TESTING_REST_PUBLISHER_TOPICS:
      overrides?.env?.['KAFKA_TESTING_REST_PUBLISHER_TOPICS'] ?? '[]',
  };

  const logger = createConsoleLogger();
  let kafka: KafkaPorts | undefined;
  if (overrides?.groupAdmin !== undefined || overrides?.publisher !== undefined) {
    const loaded = loadConfig(env);
    if (loaded.kind === 'error') throw new Error('Invalid integration test configuration');
    const prepared = prepareConfig(loaded.config);
    if (prepared.kind === 'error') throw new Error('Invalid integration test configuration');
    const realKafka = createKafkaPorts(prepared.config, logger);
    const injectedGroupAdmin = overrides.groupAdmin;
    const injectedPublisher = overrides.publisher;
    kafka = {
      ...realKafka,
      ...(injectedPublisher === undefined
        ? {}
        : {
            publisher: {
              ...injectedPublisher,
              close: async (): Promise<void> => {
                await Promise.allSettled([injectedPublisher.close(), realKafka.publisher.close()]);
              },
            },
          }),
      ...(injectedGroupAdmin === undefined
        ? {}
        : {
            groupAdmin: {
              deleteGroup: injectedGroupAdmin.deleteGroup,
              close: async (): Promise<void> => {
                await Promise.allSettled([
                  injectedGroupAdmin.close(),
                  realKafka.groupAdmin.close(),
                ]);
              },
            },
          }),
    };
  }

  const application = await startApplication({
    env,
    logger,
    installSignalHandlers: false,
    ...(kafka === undefined ? {} : { kafka }),
  });
  const address = application.address();
  if (address === undefined) {
    await application.shutdown('integration-startup-failed');
    throw new Error('Application did not expose an HTTP address');
  }

  let shutdownPromise: Promise<void> | undefined;
  const shutdown = (): Promise<void> => {
    shutdownPromise ??= application.shutdown('integration-test-cleanup');
    return shutdownPromise;
  };
  let cleanupPromise: Promise<void> | undefined;
  const cleanup = (): Promise<void> => {
    cleanupPromise ??= (async (): Promise<void> => {
      try {
        await shutdown();
      } catch (error: unknown) {
        logCleanupFailure('test application shutdown', error);
      } finally {
        await cleanupTopics();
      }
    })();
    return cleanupPromise;
  };

  return {
    baseUrl: `http://127.0.0.1:${address.port}`,
    shutdown,
    cleanup,
    test: application.test,
  };
}

export async function httpJson(
  baseUrl: string,
  method: string,
  path: string,
  body?: unknown,
): Promise<HttpJsonResponse> {
  const response = await fetch(new URL(path, baseUrl), {
    method,
    ...(body === undefined
      ? {}
      : { headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) }),
  });
  const text = await response.text();
  let parsed: unknown;
  if (text.length > 0) {
    try {
      parsed = JSON.parse(text) as unknown;
    } catch {
      parsed = text;
    }
  }
  return {
    status: response.status,
    headers: Object.fromEntries(response.headers.entries()),
    body: parsed,
  };
}

function toBuffer(value: Uint8Array | string | null | undefined): Buffer | undefined {
  if (value === null || value === undefined) return undefined;
  return typeof value === 'string' ? Buffer.from(value) : Buffer.from(value);
}

function toHeaders(headers: IHeaders | undefined): RawHeader[] {
  const result: RawHeader[] = [];
  for (const [name, rawValue] of Object.entries(headers ?? {})) {
    const values = Array.isArray(rawValue) ? rawValue : [rawValue];
    for (const value of values) result.push({ name, value: toBuffer(value) });
  }
  return result;
}

/** Читает исходные байты отдельной группой KafkaJS с начала топика. */
export async function readRawMessages(
  topic: string,
  count: number,
  timeoutMs = 5_000,
): Promise<RawMessage[]> {
  if (!Number.isInteger(count) || count < 1) throw new RangeError('count must be positive');
  assertTimeout(timeoutMs);

  const consumer: Consumer = new Kafka({
    clientId: `kafka-testing-rest-integration-reader-${randomUUID()}`,
    brokers: [getBrokerAddress()],
  }).consumer({ groupId: `kafka-testing-rest-integration-reader-${randomUUID()}` });
  const messages: RawMessage[] = [];
  let timer: NodeJS.Timeout | undefined;

  try {
    const result = await new Promise<RawMessage[]>((resolve, reject) => {
      timer = setTimeout(
        () => reject(new Error(`Timed out reading ${count} Kafka messages`)),
        timeoutMs,
      );
      const finish = (): void => {
        if (messages.length >= count) resolve(messages.slice(0, count));
      };
      void consumer
        .connect()
        .then(() => consumer.subscribe({ topic, fromBeginning: true }))
        .then(() =>
          consumer.run({
            eachMessage: async ({ message }) => {
              if (messages.length >= count) return;
              messages.push({
                key: toBuffer(message.key),
                value: toBuffer(message.value),
                headers: toHeaders(message.headers),
              });
              finish();
            },
          }),
        )
        .catch(reject);
    });
    return result;
  } finally {
    if (timer !== undefined) clearTimeout(timer);
    try {
      await consumer.disconnect();
    } catch (error: unknown) {
      logCleanupFailure('Kafka raw reader disconnect', error);
    }
  }
}

/** Удаляет созданные harness-топики; ошибки удаления только журналируются. */
export async function cleanup(): Promise<void> {
  await cleanupTopics();
}
